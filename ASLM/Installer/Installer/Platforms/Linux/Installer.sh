# Build machine (invoked by ASLM.Linux.csproj during a Release publish):
#   Installer.sh --package BUILD_ROOT OUTPUT VERSION DOWNLOAD_URL
#   Validates the publish output, then renders the installer template below the
#   marker into OUTPUT with the version and download URL substituted. The release
#   workflow stamps the archive digest into the rendered file afterwards.
#
# End user (rendered ASLM-linux-amd64.sh, no arguments):
#   Confirms the installation, elevates with sudo, downloads the
#   ASLM-linux-amd64.tar.gz release asset and installs ASLM under /opt/ASLM.

set -eu

# Renders the embedded installer template into a standalone download-and-install script.
package_installer()
{
    local build_root output version download_url script_dir stage executable required
    set -o pipefail
    [ "$#" -eq 5 ] || { echo 'Usage: Installer.sh --package BUILD_ROOT OUTPUT VERSION DOWNLOAD_URL' >&2; return 1; }
    build_root=$(realpath "$2")
    output=$(realpath -m "$3")
    version=$4
    download_url=$5
    script_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
    [[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]] || { echo 'Invalid installer version.' >&2; return 1; }
    case "$download_url" in
        https://*) ;;
        *) echo 'The download URL must use HTTPS.' >&2; return 1 ;;
    esac

    # Fail before producing an installer if publish omitted an executable, runtime or first-run templates.
    for executable in ASLM App/ASLM Patcher/aslm-patcher; do test -x "$build_root/$executable"; done
    for required in libcoreclr.so libhostfxr.so libhostpolicy.so seed/Data/App/ASLM_Data.json hicolor/scalable/apps/appicon.svg; do
        test -f "$build_root/App/$required"
    done
    mkdir -p "$script_dir/../../obj" "$(dirname -- "$output")"
    stage=$(mktemp -d "$script_dir/../../obj/linux-installer.XXXXXXXX")
    trap 'rm -rf -- "$stage"' EXIT
    trap 'exit 1' HUP INT TERM

    # The installer template is this same file below the marker; placeholders are filled in here.
    awk 'found { print } /^#__ASLM_INSTALLER_TEMPLATE_BELOW__$/ { found = 1 }' "${BASH_SOURCE[0]}" > "$stage/template.sh"
    grep -q '@ASLM_DOWNLOAD_URL@' "$stage/template.sh" ||
        { echo 'The installer template or its placeholders are missing.' >&2; return 1; }

    # Publish atomically so a canceled build cannot leave a seemingly usable, truncated installer.
    # The digest placeholder is left empty here; the release workflow knows the final archive hash.
    sed -e "s|@ASLM_DOWNLOAD_URL@|$download_url|g" \
        -e "s/@ASLM_VERSION@/$version/g" \
        -e "s/@ASLM_ARCHIVE_SHA256@//g" \
        "$stage/template.sh" > "$stage/installer.sh"
    if grep -q '@ASLM_' "$stage/installer.sh"; then
        echo 'Unsubstituted installer placeholders remain.' >&2
        return 1
    fi
    chmod 755 "$stage/installer.sh"
    mv -f -- "$stage/installer.sh" "$output"
    rm -rf -- "$stage"
    trap - EXIT HUP INT TERM
    printf 'Linux installer: %s\n' "$output"
}

if [ "${1:-}" = '--package' ]; then
    package_installer "$@"
    exit
fi

# Everything below the marker ships to end users; the packer renders it verbatim.
#__ASLM_INSTALLER_TEMPLATE_BELOW__
#!/bin/sh
# Copyright NEXTGGTECH. Apache License 2.0.
#
# Downloads the ASLM-linux-amd64.tar.gz release asset and installs ASLM
# system-wide. Generated by the ASLM release build; do not edit the rendered file.

set -eu

install_dir=/opt/ASLM
command_path=/usr/local/bin/aslm
desktop_path=/usr/local/share/applications/com.nextggtech.aslm.desktop
root_name=ASLM-linux-amd64
archive_name=ASLM-linux-amd64.tar.gz
download_url='@ASLM_DOWNLOAD_URL@'
archive_digest='@ASLM_ARCHIVE_SHA256@'
version='@ASLM_VERSION@'
stage=
payload=
replaced=0
installed=0
command_created=0
desktop_written=0
completed=0

# Reports an installation error without starting the application as root.
fail()
{
    printf 'ASLM: %s\n' "$*" >&2
    exit 1
}

# Restores a previous system installation on failure and removes this invocation's staging files.
cleanup()
{
    result=$?
    trap - 0
    retain=0
    if [ "$completed" -ne 1 ]; then
        # Undo desktop integration before restoring the program directory.
        if [ "$desktop_written" -eq 1 ]; then
            if [ -f "$stage/previous.desktop" ]; then
                cp -p "$stage/previous.desktop" "$desktop_path" || retain=1
            else
                rm -f -- "$desktop_path" || retain=1
            fi
        fi
        if [ "$command_created" -eq 1 ]; then rm -f -- "$command_path" || retain=1; fi
        if [ "$installed" -eq 1 ]; then mv -- "$install_dir" "$stage/failed" || retain=1; fi
        if [ "$replaced" -eq 1 ]; then mv -- "$stage/previous" "$install_dir" || retain=1; fi
    fi

    # The private staging directory is created under /opt, on the same filesystem as the installation.
    if [ "$retain" -eq 0 ]; then
        case "$stage" in /opt/.ASLM-install.*) rm -rf -- "$stage" ;; esac
    else
        printf 'ASLM: recovery files retained in %s\n' "$stage" >&2
    fi
    exit "$result"
}

# Prints what the installer will do and requires an explicit yes before any system change.
confirm_installation()
{
    printf '%s\n' \
        "ASLM ${version} will be installed:" \
        '' \
        "  - download ${archive_name} from" \
        "    ${download_url}" \
        "  - install the application to ${install_dir} (system-wide)" \
        "  - create the 'aslm' command (${command_path})" \
        '  - add an application-menu entry' \
        '  - install missing system packages with apt' \
        '' \
        'Administrator privileges are required.'
    printf 'Proceed with the installation? [yes/no] '
    read reply || fail 'No confirmation was received.'
    case "$reply" in
        [Yy]|[Yy][Ee][Ss]) ;;
        *) printf 'Installation canceled.\n'; exit 0 ;;
    esac
}

# Installs only missing native runtime packages for the supported Ubuntu release; .NET is bundled.
install_dependencies()
{
    . /etc/os-release
    [ "$ID" = ubuntu ] && [ "$VERSION_ID" = 26.04 ] ||
        fail 'Automatic installation currently requires Ubuntu 26.04 AMD64.'

    missing=
    for package in ca-certificates curl libbrotli1 libc6 libgcc-s1 libgssapi-krb5-2 libicu78 \
        libssl3t64 libstdc++6 tzdata zlib1g libgtk-4-1 libwebkitgtk-6.0-4 \
        libfontconfig1 libfreetype6 xdg-utils; do
        if [ "$(dpkg-query -W -f='${Status}' "$package" 2>/dev/null || true)" != 'install ok installed' ]; then
            missing="$missing $package"
        fi
    done
    if [ -n "$missing" ]; then
        apt-get update
        # Package names come only from the fixed list above, not from installer arguments or user data.
        apt-get install --no-install-recommends -y $missing
    fi
}

# Downloads the release archive; the digest, when stamped by the release workflow, pins the exact asset.
download_payload()
{
    curl --fail --location --show-error --retry 3 \
        --output "$stage/$archive_name" "$download_url" ||
        fail "Could not download ${archive_name}; check the network connection."
    if [ -n "$archive_digest" ]; then
        printf '%s  %s\n' "$archive_digest" "$stage/$archive_name" | sha256sum --check --status ||
            fail 'The downloaded ASLM archive is damaged or was modified.'
    fi
}

# Validates the downloaded release archive and stages the system installation layout.
stage_payload()
{
    # Every entry must live under the single expected root folder, with no traversal paths.
    entries=$(tar -tzf "$stage/$archive_name") ||
        fail 'The downloaded file is not a valid ASLM archive.'
    if printf '%s\n' "$entries" | grep -v "^${root_name}/" | grep -q .; then
        fail 'Unexpected archive layout.'
    fi
    if printf '%s\n' "$entries" | grep -q '\.\.'; then
        fail 'Unexpected archive layout.'
    fi
    # Link or device entries could escape the staging directory during extraction.
    tar -tvzf "$stage/$archive_name" |
        awk 'substr($0, 1, 1) != "-" && substr($0, 1, 1) != "d" { bad = 1 } END { exit bad }' ||
        fail 'The ASLM archive contains a link or device entry.'
    for required in ASLM App/ASLM Patcher/aslm-patcher \
        App/libcoreclr.so App/libhostfxr.so App/libhostpolicy.so \
        App/seed/Data/App/ASLM_Data.json App/hicolor/scalable/apps/appicon.svg; do
        printf '%s\n' "$entries" | grep -qx "${root_name}/${required}" ||
            fail "The ASLM archive is incomplete: ${required}."
    done

    mkdir "$stage/extract" "$stage/new"
    tar -xzf "$stage/$archive_name" -C "$stage/extract" --no-same-owner
    payload="$stage/extract/$root_name"
    # The launcher bootstraps per-user copies from the base archive with these exact executable modes.
    chmod 755 "$payload/ASLM" "$payload/App/ASLM" "$payload/Patcher/aslm-patcher"
    mv -- "$payload/ASLM" "$stage/new/ASLM"
    tar -C "$payload" -czf "$stage/new/aslm-base.tar.gz" App Patcher
    cp -- "$payload/App/hicolor/scalable/apps/appicon.svg" "$stage/new/appicon.svg"
    chmod 755 "$stage/new" "$stage/new/ASLM"
    chmod 644 "$stage/new/aslm-base.tar.gz" "$stage/new/appicon.svg"
}

# Replaces only the shared launcher/base archive and registers the normal-user desktop entry.
install_application()
{
    # Refuse to replace unrelated files or follow installation-directory links.
    [ ! -L "$install_dir" ] || fail "$install_dir is a symbolic link."
    if [ -e "$install_dir" ]; then
        [ -d "$install_dir" ] && [ -f "$install_dir/ASLM" ] && [ -f "$install_dir/aslm-base.tar.gz" ] ||
            fail "$install_dir is not an ASLM installation."
    fi
    if [ -e "$command_path" ] || [ -L "$command_path" ]; then
        [ -L "$command_path" ] && [ "$(readlink "$command_path")" = "$install_dir/ASLM" ] ||
            fail "$command_path already belongs to another application."
    fi
    [ ! -L "$desktop_path" ] || fail "$desktop_path is a symbolic link."
    if [ -e "$desktop_path" ]; then
        grep -qx 'Exec=/opt/ASLM/ASLM' "$desktop_path" || fail "$desktop_path belongs to another application."
        cp -p "$desktop_path" "$stage/previous.desktop"
    fi

    # Directory renames keep a complete previous installation available until integration succeeds.
    if [ -d "$install_dir" ]; then
        mv -- "$install_dir" "$stage/previous"
        replaced=1
    fi
    mv -- "$stage/new" "$install_dir"
    installed=1
    mkdir -p /usr/local/bin /usr/local/share/applications
    if [ ! -L "$command_path" ]; then
        ln -s "$install_dir/ASLM" "$command_path"
        command_created=1
    fi
    # Use a regular source file for both initial creation and replacement of the desktop entry.
    cat > "$stage/aslm.desktop" <<'DESKTOP'
[Desktop Entry]
Type=Application
Name=ASLM
Comment=Advanced System Language Models
Exec=/opt/ASLM/ASLM
Icon=/opt/ASLM/appicon.svg
Terminal=false
Categories=Utility;
DESKTOP
    desktop_written=1
    install -m 644 "$stage/aslm.desktop" "$desktop_path"
    completed=1
}

# Confirm as the invoking user first; only an explicit yes leads to the administrator prompt.
[ "$(uname -s)" = Linux ] && [ "$(uname -m)" = x86_64 ] || fail 'This installer requires Linux AMD64.'
case "$download_url" in @*) fail 'Run the packaged installer, not its source template.' ;; esac
installer=$(readlink -f -- "$0")
if [ "$(id -u)" -ne 0 ]; then
    [ "$#" -eq 0 ] || fail 'This installer takes no arguments; the system directory is /opt/ASLM.'
    confirm_installation
    command -v sudo >/dev/null 2>&1 || fail 'Run this installer with administrator privileges.'
    exec sudo /bin/sh "$installer" --confirmed
fi
if [ "${1:-}" = '--confirmed' ]; then
    [ "$#" -eq 1 ] || fail 'This installer takes no arguments; the system directory is /opt/ASLM.'
else
    # A direct sudo invocation still needs explicit consent before anything is touched.
    [ "$#" -eq 0 ] || fail 'This installer takes no arguments; the system directory is /opt/ASLM.'
    confirm_installation
fi
umask 022
mkdir -p /opt
stage=$(mktemp -d /opt/.ASLM-install.XXXXXXXX)
trap cleanup 0
trap 'exit 1' HUP INT TERM
install_dependencies
download_payload
stage_payload
install_application
if command -v update-desktop-database >/dev/null 2>&1; then
    update-desktop-database /usr/local/share/applications || true
fi
printf 'ASLM %s installed in %s.\nRun ASLM from the application menu or with: aslm\nDo not run ASLM with sudo.\n' "$version" "$install_dir"
exit 0
