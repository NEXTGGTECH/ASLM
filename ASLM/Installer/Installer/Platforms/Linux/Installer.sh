# Build machine (invoked by ASLM.Linux.csproj during a Release publish):
#   Installer.sh --package BUILD_ROOT OUTPUT VERSION DOWNLOAD_URL
#   Validates the publish output, then renders the installer template below the
#   marker into OUTPUT with the version and download URL substituted. The release
#   workflow stamps the archive digest into the rendered file afterwards.
#
# End user (rendered ASLM-linux-amd64.sh, no arguments):
#   Confirms the installation, elevates with sudo, downloads the
#   ASLM-linux-amd64.tar.gz release asset and installs ASLM under /opt/ASLM.

set -eu

# Renders the embedded installer template into a standalone download-and-install script.
package_installer()
{
    local build_root output version download_url script_dir stage executable required
    set -o pipefail
    [ "$#" -eq 5 ] || { echo 'Usage: Installer.sh --package BUILD_ROOT OUTPUT VERSION DOWNLOAD_URL' >&2; return 1; }
    build_root=$(realpath "$2")
    output=$(realpath -m "$3")
    version=$4
    download_url=$5
    script_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
    [[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]] || { echo 'Invalid installer version.' >&2; return 1; }
    case "$download_url" in
        https://*) ;;
        *) echo 'The download URL must use HTTPS.' >&2; return 1 ;;
    esac

    # Fail before producing an installer if publish omitted an executable, runtime or first-run templates.
    for executable in ASLM App/ASLM Patcher/aslm-patcher; do test -x "$build_root/$executable"; done
    for required in libcoreclr.so libhostfxr.so libhostpolicy.so seed/Data/App/ASLM_Data.json hicolor/scalable/apps/appicon.svg; do
        test -f "$build_root/App/$required"
    done
    mkdir -p "$script_dir/../../obj" "$(dirname -- "$output")"
    stage=$(mktemp -d "$script_dir/../../obj/linux-installer.XXXXXXXX")
    trap 'rm -rf -- "$stage"' EXIT
    trap 'exit 1' HUP INT TERM

    # The installer template is this same file below the marker; placeholders are filled in here.
    awk 'found { print } /^#__ASLM_INSTALLER_TEMPLATE_BELOW__$/ { found = 1 }' "${BASH_SOURCE[0]}" > "$stage/template.sh"
    grep -q '@ASLM_DOWNLOAD_URL@' "$stage/template.sh" ||
        { echo 'The installer template or its placeholders are missing.' >&2; return 1; }

    # Publish atomically so a canceled build cannot leave a seemingly usable, truncated installer.
    # The digest placeholder is left empty here; the release workflow knows the final archive hash.
    sed -e "s|@ASLM_DOWNLOAD_URL@|$download_url|g" \
        -e "s/@ASLM_VERSION@/$version/g" \
        -e "s/@ASLM_ARCHIVE_SHA256@//g" \
        "$stage/template.sh" > "$stage/installer.sh"
    if grep -q '@ASLM_' "$stage/installer.sh"; then
        echo 'Unsubstituted installer placeholders remain.' >&2
        return 1
    fi
    chmod 755 "$stage/installer.sh"
    mv -f -- "$stage/installer.sh" "$output"
    rm -rf -- "$stage"
    trap - EXIT HUP INT TERM
    printf 'Linux installer: %s\n' "$output"
}

if [ "${1:-}" = '--package' ]; then
    package_installer "$@"
    exit
fi

# Everything below the marker ships to end users; the packer renders it verbatim.
#__ASLM_INSTALLER_TEMPLATE_BELOW__
#!/bin/sh
# Copyright NEXTGGTECH. Apache License 2.0.
#
# Downloads the ASLM-linux-amd64.tar.gz release asset and installs ASLM
# system-wide. Generated by the ASLM release build; do not edit the rendered file.

set -eu

install_dir=/opt/ASLM
command_path=/usr/local/bin/aslm
desktop_path=/usr/local/share/applications/com.nextggtech.aslm.desktop
root_name=ASLM-linux-amd64
archive_name=ASLM-linux-amd64.tar.gz
download_url='@ASLM_DOWNLOAD_URL@'
archive_digest='@ASLM_ARCHIVE_SHA256@'
version='@ASLM_VERSION@'
archive_source=
package_manager=
family=
stage=
payload=
replaced=0
installed=0
command_created=0
desktop_written=0
completed=0

# Reports an installation error without starting the application as root.
fail()
{
    printf 'ASLM: %s\n' "$*" >&2
    exit 1
}

# Restores a previous system installation on failure and removes this invocation's staging files.
cleanup()
{
    result=$?
    trap - 0
    retain=0
    if [ "$completed" -ne 1 ]; then
        # Undo desktop integration before restoring the program directory.
        if [ "$desktop_written" -eq 1 ]; then
            if [ -f "$stage/previous.desktop" ]; then
                cp -p "$stage/previous.desktop" "$desktop_path" || retain=1
            else
                rm -f -- "$desktop_path" || retain=1
            fi
        fi
        if [ "$command_created" -eq 1 ]; then rm -f -- "$command_path" || retain=1; fi
        if [ "$installed" -eq 1 ]; then mv -- "$install_dir" "$stage/failed" || retain=1; fi
        if [ "$replaced" -eq 1 ]; then mv -- "$stage/previous" "$install_dir" || retain=1; fi
    fi

    # The private staging directory is created under /opt, on the same filesystem as the installation.
    if [ "$retain" -eq 0 ]; then
        case "$stage" in /opt/.ASLM-install.*) rm -rf -- "$stage" ;; esac
    else
        printf 'ASLM: recovery files retained in %s\n' "$stage" >&2
    fi
    exit "$result"
}

# Prints what the installer will do and requires an explicit yes before any system change.
confirm_installation()
{
    printf '%s\n' "ASLM ${version} will be installed:" ''
    if [ -n "$archive_source" ]; then
        printf '%s\n' "  - read the local release archive: ${archive_source}"
    else
        printf '%s\n' "  - download ${archive_name} from" "    ${download_url}"
    fi
    printf '%s\n' \
        "  - install the application to ${install_dir} (system-wide)" \
        "  - create the 'aslm' command (${command_path})" \
        '  - add an application-menu entry' \
        '  - check the actual native libraries before replacing an existing installation'
    if [ -n "$package_manager" ]; then
        printf '  - install missing system packages with %s if required\n' "$package_manager"
    else
        printf '%s\n' '  - require native dependencies to be installed manually if any are missing'
    fi
    printf '\nAdministrator privileges are required.\n'
    printf 'Proceed with the installation? [yes/no] '
    read reply || fail 'No confirmation was received.'
    case "$reply" in
        [Yy]|[Yy][Ee][Ss]) ;;
        *) printf 'Installation canceled.\n'; exit 0 ;;
    esac
}

# Select dependency package names from distribution metadata or the available package manager.
detect_distribution()
{
    ID= ID_LIKE=
    family=manual
    package_manager=
    if [ -r "${1:-/etc/os-release}" ]; then
        . "${1:-/etc/os-release}"
    fi
    case " $ID $ID_LIKE " in
        *' ubuntu '*|*' debian '*) family=debian; package_manager=apt-get ;;
        *' rhel '*|*' centos '*|*' almalinux '*|*' rocky '*) family=el; package_manager=dnf ;;
        *' fedora '*) family=fedora; package_manager=dnf ;;
        *' opensuse '*|*' opensuse-leap '*|*' opensuse-tumbleweed '*|*' suse '*)
            family=suse; package_manager=zypper ;;
        *' arch '*|*' archlinux '*) family=arch; package_manager=pacman ;;
    esac
    if [ -n "$package_manager" ] && command -v "$package_manager" >/dev/null 2>&1; then
        return
    fi

    # Unknown distributions can still use a supported package manager or supply their dependencies themselves.
    family=manual
    package_manager=
    for manager in apt-get dnf zypper pacman; do
        if command -v "$manager" >/dev/null 2>&1; then
            package_manager=$manager
            case "$manager" in
                apt-get) family=debian ;;
                dnf) family=fedora ;;
                zypper) family=suse ;;
                pacman) family=arch ;;
            esac
            break
        fi
    done
}

# Prepare archive and download utilities before the application can probe native dependencies.
install_installer_tools()
{
    utilities='awk tar gzip sha256sum'
    if [ -z "$archive_source" ]; then utilities="$utilities curl"; fi
    missing_tools=
    for utility in $utilities; do
        if ! command -v "$utility" >/dev/null 2>&1; then
            missing_tools="$missing_tools $utility"
        fi
    done
    [ -n "$missing_tools" ] || return 0

    # Install only transport and archive tools until the application can check the actual UI libraries.
    case "$family" in
        debian)
            apt-get update
            apt-get install --no-install-recommends -y ca-certificates curl tar gzip gawk coreutils ;;
        fedora|el) dnf install -y ca-certificates curl tar gzip gawk coreutils ;;
        suse)
            zypper --non-interactive refresh
            zypper --non-interactive --no-refresh install --no-recommends \
                ca-certificates curl tar gzip gawk coreutils ;;
        arch) pacman -S --needed --noconfirm ca-certificates curl tar gzip gawk coreutils ;;
        *) fail "Install the missing installer tools manually, then retry:${missing_tools}." ;;
    esac

    # Do not misreport unavailable utilities as a corrupt download or an incompatible application.
    for utility in $utilities; do
        command -v "$utility" >/dev/null 2>&1 || fail "The required installer tool '${utility}' is unavailable."
    done
}

# Return an installable Debian package version, including an already installed package.
debian_candidate()
{
    apt-cache policy "$1" | awk '/Candidate:/ && $2 != "(none)" { print $2; exit }'
}

# Select an installable package from the named alternatives without pinning one distro's ICU or OpenSSL ABI.
select_debian_package()
{
    for candidate in "$@"; do
        if [ -n "$(debian_candidate "$candidate")" ]; then printf '%s\n' "$candidate"; return; fi
    done
    fail "No supported package is available for: $*."
}

# Install Debian-family runtime libraries using the enabled repositories.
install_debian_dependencies()
{
    apt-get update
    [ -n "$(debian_candidate libwebkitgtk-6.0-4)" ] ||
        fail 'WebKitGTK API 6.0 is unavailable. Enable the official repository providing libwebkitgtk-6.0-4.'
    icu_packages=$(apt-cache pkgnames | grep -E '^libicu[0-9]+$' | sort -Vr) || true
    [ -n "$icu_packages" ] || fail 'No ICU runtime package is available in the enabled repositories.'
    # ICU names originate in the package index and are restricted to the exact pattern above.
    icu_package=$(select_debian_package $icu_packages)
    ssl_package=$(select_debian_package libssl3t64 libssl3)
    apt-get install --no-install-recommends -y ca-certificates curl libc6 libgcc-s1 \
        libgssapi-krb5-2 "$icu_package" "$ssl_package" libstdc++6 tzdata zlib1g \
        libgtk-4-1 libwebkitgtk-6.0-4 libfontconfig1 libfreetype6 xdg-utils pkexec tar gzip
}

# Read the newest installed or available RPM version from DNF's package listing.
dnf_candidate()
{
    dnf -q list --showduplicates "$1" 2>/dev/null |
        awk -v package="$1" 'index($1, package ".") == 1 { print $2 }' | sort -V | tail -n 1
}

# Install Fedora or enterprise-Linux libraries without automatically adding EPEL or CRB repositories.
install_dnf_dependencies()
{
    if [ -z "$(dnf_candidate webkitgtk6.0)" ]; then
        if [ "$family" = el ]; then
            fail 'WebKitGTK API 6.0 is unavailable. Enable the matching EPEL and CRB repositories manually, then rerun this installer.'
        fi
        fail 'WebKitGTK API 6.0 is unavailable in the enabled repositories (package webkitgtk6.0).'
    fi
    dnf install -y ca-certificates curl glibc libgcc krb5-libs libicu openssl-libs \
        libstdc++ tzdata zlib gtk4 webkitgtk6.0 fontconfig freetype xdg-utils polkit tar gzip
}

# Read a package edition from Zypper's machine-readable search results.
zypper_candidate()
{
    zypper --xmlout --non-interactive --no-refresh search --match-exact --details "$1" |
        sed -n 's/.*edition="\([^"]*\)".*/\1/p' | sort -V | tail -n 1
}

# Install openSUSE runtime libraries from the already configured repositories.
install_suse_dependencies()
{
    zypper --non-interactive refresh
    [ -n "$(zypper_candidate libwebkitgtk-6_0-4)" ] ||
        fail 'WebKitGTK API 6.0 is unavailable in the enabled repositories (package libwebkitgtk-6_0-4).'
    zypper --non-interactive --no-refresh install --no-recommends ca-certificates curl \
        glibc libgcc_s1 krb5 libicu libopenssl3 libstdc++6 timezone libz1 \
        libgtk-4-1 libwebkitgtk-6_0-4 fontconfig libfreetype6 xdg-utils pkexec gawk tar gzip
}

# Install Arch packages against its synchronized database without performing an unsupported partial upgrade.
install_arch_dependencies()
{
    pacman -S --needed --noconfirm ca-certificates curl glibc gcc-libs krb5 icu openssl \
        tzdata zlib gtk4 webkitgtk-6.0 fontconfig freetype2 xdg-utils polkit tar gzip ||
        fail 'Package installation failed. Run a full system upgrade with pacman -Syu, then retry.'
}

# Install the selected family's native runtime dependencies; .NET itself is bundled with ASLM.
install_dependencies()
{
    case "$family" in
        debian) install_debian_dependencies ;;
        fedora|el) install_dnf_dependencies ;;
        suse) install_suse_dependencies ;;
        arch) install_arch_dependencies ;;
        *) fail 'No supported package manager was found. Install the reported native dependencies manually, then rerun this installer.' ;;
    esac
}

# Accept compatible native libraries on any distribution, repairing missing dependencies only when needed.
ensure_runtime_dependencies()
{
    if "$payload/App/ASLM" --check-runtime > "$stage/runtime-check.log" 2>&1; then
        return
    fi

    # Show the actual loader and GTK errors before attempting distribution-specific package installation.
    cat "$stage/runtime-check.log" >&2
    install_dependencies
    if "$payload/App/ASLM" --check-runtime > "$stage/runtime-check.log" 2>&1; then
        return
    fi
    cat "$stage/runtime-check.log" >&2
    fail 'ASLM cannot load its native runtime libraries. The existing installation was kept. Install the reported dependencies manually, then retry.'
}

# Downloads the release archive; the digest, when stamped by the release workflow, pins the exact asset.
download_payload()
{
    if [ -n "$archive_source" ]; then
        cp -- "$archive_source" "$stage/$archive_name" || fail 'Could not read the local release archive.'
    else
        curl --fail --location --show-error --retry 3 \
            --output "$stage/$archive_name" "$download_url" ||
            fail "Could not download ${archive_name}; check the network connection."
    fi
    if [ -n "$archive_digest" ]; then
        printf '%s  %s\n' "$archive_digest" "$stage/$archive_name" | sha256sum --check --status ||
            fail 'The downloaded ASLM archive is damaged or was modified.'
    fi
}

# Validates the downloaded release archive and stages the system installation layout.
stage_payload()
{
    # Every entry must live under the single expected root folder, with no traversal paths.
    entries=$(tar -tzf "$stage/$archive_name") ||
        fail 'The downloaded file is not a valid ASLM archive.'
    if printf '%s\n' "$entries" | grep -v "^${root_name}/" | grep -q .; then
        fail 'Unexpected archive layout.'
    fi
    if printf '%s\n' "$entries" | grep -q '\.\.'; then
        fail 'Unexpected archive layout.'
    fi
    # Link or device entries could escape the staging directory during extraction.
    tar -tvzf "$stage/$archive_name" |
        awk 'substr($0, 1, 1) != "-" && substr($0, 1, 1) != "d" { bad = 1 } END { exit bad }' ||
        fail 'The ASLM archive contains a link or device entry.'
    for required in ASLM App/ASLM Patcher/aslm-patcher \
        App/libcoreclr.so App/libhostfxr.so App/libhostpolicy.so \
        App/seed/Data/App/ASLM_Data.json App/hicolor/scalable/apps/appicon.svg; do
        printf '%s\n' "$entries" | grep -qx "${root_name}/${required}" ||
            fail "The ASLM archive is incomplete: ${required}."
    done

    mkdir "$stage/extract" "$stage/new"
    tar -xzf "$stage/$archive_name" -C "$stage/extract" --no-same-owner
    payload="$stage/extract/$root_name"
    mv -- "$payload/ASLM" "$stage/new/ASLM"
    # The launcher sets up each user's copy from the release archive itself, as after a self-update of this folder.
    mv -- "$stage/$archive_name" "$stage/new/aslm-base.tar.gz"
    cp -- "$payload/App/hicolor/scalable/apps/appicon.svg" "$stage/new/appicon.svg"
    # The patcher compares this version with later releases to decide whether they update this folder too.
    printf '{\n  "app": "ASLM",\n  "version": "%s",\n  "sharedInstallPath": "%s"\n}\n' \
        "$version" "$install_dir" > "$stage/new/install-manifest.json"
    chmod 755 "$stage/new" "$stage/new/ASLM"
    chmod 644 "$stage/new/aslm-base.tar.gz" "$stage/new/appicon.svg" "$stage/new/install-manifest.json"
}

# Replaces only the shared launcher/base archive and registers the normal-user desktop entry.
install_application()
{
    # Refuse to replace unrelated files or follow installation-directory links.
    [ ! -L "$install_dir" ] || fail "$install_dir is a symbolic link."
    if [ -e "$install_dir" ]; then
        [ -d "$install_dir" ] && [ -f "$install_dir/ASLM" ] && [ -f "$install_dir/aslm-base.tar.gz" ] ||
            fail "$install_dir is not an ASLM installation."
    fi
    if [ -e "$command_path" ] || [ -L "$command_path" ]; then
        [ -L "$command_path" ] && [ "$(readlink "$command_path")" = "$install_dir/ASLM" ] ||
            fail "$command_path already belongs to another application."
    fi
    [ ! -L "$desktop_path" ] || fail "$desktop_path is a symbolic link."
    if [ -e "$desktop_path" ]; then
        grep -qx 'Exec=/opt/ASLM/ASLM' "$desktop_path" || fail "$desktop_path belongs to another application."
        cp -p "$desktop_path" "$stage/previous.desktop"
    fi

    # Directory renames keep a complete previous installation available until integration succeeds.
    if [ -d "$install_dir" ]; then
        mv -- "$install_dir" "$stage/previous"
        replaced=1
    fi
    mv -- "$stage/new" "$install_dir"
    installed=1
    mkdir -p /usr/local/bin /usr/local/share/applications
    if [ ! -L "$command_path" ]; then
        ln -s "$install_dir/ASLM" "$command_path"
        command_created=1
    fi
    # Use a regular source file for both initial creation and replacement of the desktop entry.
    cat > "$stage/aslm.desktop" <<'DESKTOP'
[Desktop Entry]
Type=Application
Name=ASLM
Comment=Advanced System Language Models
Exec=/opt/ASLM/ASLM
Icon=/opt/ASLM/appicon.svg
Terminal=false
Categories=Utility;
DESKTOP
    desktop_written=1
    install -m 644 "$stage/aslm.desktop" "$desktop_path"
    completed=1
}

# Parse a local release archive without changing the normal installation destination or consent requirement.
parse_arguments()
{
    confirmed=0
    while [ "$#" -gt 0 ]; do
        case "$1" in
            --archive)
                [ "$#" -ge 2 ] && [ -z "$archive_source" ] || fail 'Usage: ASLM-linux-amd64.sh [--archive FILE].'
                archive_source=$(readlink -f -- "$2") || fail 'The local release archive cannot be resolved.'
                [ -f "$archive_source" ] || fail 'The local release archive does not exist.'
                shift 2 ;;
            --confirmed)
                [ "$(id -u)" -eq 0 ] && [ "$confirmed" -eq 0 ] || fail 'Invalid internal confirmation argument.'
                confirmed=1
                shift ;;
            *) fail 'Usage: ASLM-linux-amd64.sh [--archive FILE].' ;;
        esac
    done
}

# Confirm as the invoking user first; only explicit consent leads to the administrator prompt.
export LC_ALL=C
[ "$(uname -s)" = Linux ] && [ "$(uname -m)" = x86_64 ] || fail 'This installer requires Linux AMD64.'
case "$download_url" in @*) fail 'Run the packaged installer, not its source template.' ;; esac
parse_arguments "$@"
detect_distribution
installer=$(readlink -f -- "$0")
if [ "$(id -u)" -ne 0 ]; then
    confirm_installation
    command -v sudo >/dev/null 2>&1 ||
        fail 'sudo is unavailable. Ask an administrator to run this installer as root.'
    if [ -n "$archive_source" ]; then
        exec sudo /bin/sh "$installer" --confirmed --archive "$archive_source"
    fi
    exec sudo /bin/sh "$installer" --confirmed
fi
[ "$confirmed" -eq 1 ] || confirm_installation
install_installer_tools
umask 022
mkdir -p /opt
stage=$(mktemp -d /opt/.ASLM-install.XXXXXXXX)
trap cleanup 0
trap 'exit 1' HUP INT TERM
download_payload
stage_payload

# Check the staged libraries before repairing native dependencies or replacing the existing application.
ensure_runtime_dependencies
install_application
if command -v update-desktop-database >/dev/null 2>&1; then
    update-desktop-database /usr/local/share/applications || true
fi
printf 'ASLM %s installed in %s.\nRun ASLM from the application menu or with: aslm\nDo not run ASLM with sudo.\n' "$version" "$install_dir"
exit 0
